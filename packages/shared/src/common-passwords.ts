/**
 * The deny list, lowercase. Built once at module load (a few thousand `Set.add` calls,
 * measured in microseconds) so every check afterwards is an O(1) hash lookup.
 */
export const COMMON_PASSWORDS: ReadonlySet<string> = new Set(
  RAW.split('\n')
    .map((line) => line.trim().toLowerCase())
    .filter((line) => line.length > 0),
);

/**
 * True when the password is on the bundled deny list.
 *
 * Matching is case-insensitive and ignores surrounding whitespace, because `Password `
 * and `password` are the same guess to an attacker running a dictionary.
 */
export function isCommonPassword(password: string): boolean {
  return COMMON_PASSWORDS.has(password.trim().toLowerCase());
}
